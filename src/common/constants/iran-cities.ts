// ورودی آزاد خریدار/فروشنده (فاصله‌ی اضافه، «شهر/استان» اضافه، ي عربی به‌جای ی فارسی) را به
// یکی از نام‌های بالا نگاشت می‌کند؛ اگر مچ پیدا نشد، خودِ متن trim‌شده را برمی‌گرداند (فلو
// مسدود نمی‌شود، فقط این آدرس با هیچ قانون ارسال شهر-محورِ فروشنده match نمی‌شود و به ردیف
// پیش‌فرض «سایر شهرها» می‌افتد)
export function normalizeIranCity(raw: string): string {
  const cleaned = raw
    .trim()
    .replace(/^(شهر|استان)\s+/, '')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک');
  const match = IRAN_CITIES.find((city) => city === cleaned);
  return match ?? cleaned;
}
