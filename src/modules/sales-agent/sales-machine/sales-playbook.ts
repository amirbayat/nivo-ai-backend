// RECOMMEND با کاتالوگ خالی: محصول الزامی نیست (§۸.۲)
export function contractFor(
  goal: TurnGoal,
  catalogSize: number,
): ReplyContract {
  const c = PLAYBOOK[goal].contract;
  if (goal === 'RECOMMEND' && catalogSize === 0) {
    return { ...c, requireProducts: 'NONE' };
  }
  return c;
}

export function renderTemplate(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_m, key: string) =>
    key in vars ? String(vars[key]) : '',
  );
}

