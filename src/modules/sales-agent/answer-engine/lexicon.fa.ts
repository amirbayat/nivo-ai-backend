export type LexEntry = { re: RegExp; token: string };

const e = (pattern: string, token: string): LexEntry => ({ re: new RegExp(pattern, 'g'), token });

export const LEXICON: LexEntry[] = [
  // پرداخت در محل قبل از پرداخت عمومی
  e('پرداخت در محل|پول در محل|پس کرایه|کش در محل', '_COD'),
  // تخفیف/چانه — برای رد کردن کش (به LLM می‌رود)
  e('تخفیف|ارزون ?تر|ارزانتر|کمتر نمیشه|کم نمیشه|چانه|قیمت آخر|آخرش چنده|بیشتر تخفیف', '_DISCOUNT'),
  e('چند میدی|چند میدین|چند میدید|چنده|چقدره|چقدر میشه|چقدر|چند تومنه|چند تومانه|چه قیمتیه|قیمتش|قیمت ها|قیمت', '_PRICE'),
  e('کی میرسه|کی میرسد|کی می رسه|چند روزه میاد|چند روزه میرسه|چند روز طول میکشه|زمان ارسال|مدت ارسال|زمان رسیدن', '_SHIP_ETA'),
  e('هزینه ارسال|هزینه پست|پیک|ارسال|پست', '_SHIP'),
  e('پس میگیرین|پس میگیرید|پس میگیری|مرجوعی|مرجوع|تعویض|برگشت|گارانتی|ضمانت', '_RETURN'),
  e('کارت به کارت|چطوری پول بدم|چطور پول بدم|روش پرداخت|راه پرداخت|چطور پرداخت کنم|چطوری پرداخت کنم|پرداخت', '_PAY'),
  e('موجودی|موجوده|موجود|هست', '_STOCK'),
  // «داری/داره» ضعیف است: فقط وقتی تنها نیت پیام باشد موجودی حساب می‌شود («تعویض داره؟» مرجوعی است)
  e('داری|دارین|دارید|داره', '_HAVE'),
];

export function applyLexicon(norm: string): string {
  let s = norm;
  for (const { re, token } of LEXICON) s = s.replace(re, ` ${token} `);
  return s.replace(/\s+/g, ' ').trim();
}

