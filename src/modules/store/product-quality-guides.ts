// قبل از export، هر ۲۱ دسته باید راهنما داشته باشد
export function getProductQualityGuide(category: string | null | undefined): QualityGuideItem[] {
  const specific = (category && CATEGORY_ITEMS[category]) || CATEGORY_ITEMS['سایر'];
  return [...COMMON_ITEMS, ...specific];
}

export const PRODUCT_QUALITY_GUIDE_CATEGORIES: readonly string[] = BUSINESS_CATEGORIES;

export function hasDedicatedGuide(category: string): boolean {
  return category in CATEGORY_ITEMS;
}
